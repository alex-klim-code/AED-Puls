import { pgTable, text, uuid, boolean, timestamp, jsonb, uniqueIndex, integer, index } from "drizzle-orm/pg-core";
import { aeds } from "./aed";
import { users, organizations } from "./identity";

export const sources = pgTable("data_sources", {
  id: uuid("id").primaryKey().defaultRandom(),
  name: text("name").notNull(),
  url: text("url").notNull(),
  license: text("license").notNull(),
  coverage: text("coverage").notNull(),
  institution: text("institution").notNull(),
  datasetId: text("dataset_id").notNull(),
  updateFrequency: text("update_frequency").notNull(),
  authoritativeScope: text("authoritative_scope").notNull(),
  status: text("status").notNull().default("not_configured"),
  statusMessage: text("status_message").notNull(),
  lastCheckedAt: timestamp("last_checked_at", { withTimezone: true }),
  key: text("key"),
  lastSuccessAt: timestamp("last_success_at", { withTimezone: true }),
  lockedUntil: timestamp("locked_until", { withTimezone: true }),
  lockToken: uuid("lock_token"),
  officialProvenance: text("official_provenance").notNull().default("UNKNOWN"),
  sourceType: text("source_type").notNull().default("unknown"),
  publisherId: text("publisher_id"),
  datasetUrl: text("dataset_url"),
  resourceId: text("resource_id"),
  provenanceEvidence: jsonb("provenance_evidence").$type<Record<string, unknown>>().notNull().default({}),
  lastUpdatedAt: timestamp("last_updated_at", { withTimezone: true }),
  lastSyncedAt: timestamp("last_synced_at", { withTimezone: true }),
}, table => [uniqueIndex("integration_source_key").on(table.key)]);
export const observations = pgTable("source_observations", {
  id: uuid("id").primaryKey().defaultRandom(),
  aedId: uuid("aed_id").references(() => aeds.id),
  primarySourceKey: text("primary_source_key"),
  removedAt: timestamp("removed_at", { withTimezone: true }),
  sourceId: uuid("source_id").references(() => sources.id),
  sourceRecordId: text("source_record_id").notNull(),
  originalRecord: jsonb("original_record").notNull(),
  sourceUrl: text("source_url").notNull(),
  license: text("license").notNull(),
  importedAt: timestamp("imported_at", { withTimezone: true }).notNull().defaultNow(),
  lastSyncedAt: timestamp("last_synced_at", { withTimezone: true }).notNull().defaultNow(),
  sourceModifiedAt: timestamp("source_modified_at", { withTimezone: true }),
  publisher: text("publisher"),
  datasetUrl: text("dataset_url"),
  resourceId: text("resource_id"),
  contentHash: text("content_hash"),
  normalizedRecord: jsonb("normalized_record").$type<Record<string, unknown>>(),
  officialProvenance: text("official_provenance").notNull().default("UNKNOWN"),
  provenanceEvidence: jsonb("provenance_evidence").$type<Record<string, unknown>>().notNull().default({}),
  publisherId: text("publisher_id"),
  datasetId: text("dataset_id"),
  datasetTitle: text("dataset_title"),
  resourceFormat: text("resource_format"),
  publishedAt: timestamp("published_at", { withTimezone: true }),
  geographicScope: text("geographic_scope"),
  referenceScope: text("reference_scope"),
  reuseConditions: jsonb("reuse_conditions").$type<Record<string, unknown>>().notNull().default({}),
}, table => [uniqueIndex("source_observation_identity").on(table.sourceId, table.sourceRecordId), index("observation_aed_link").on(table.aedId)]);
export const importJobs = pgTable("import_jobs", {
  id: uuid("id").primaryKey().defaultRandom(),
  organizationId: uuid("organization_id").references(() => organizations.id),
  userId: uuid("user_id").references(() => users.id),
  status: text("status").notNull(),
  isDemo: boolean("is_demo").notNull().default(false),
  summary: jsonb("summary").notNull().default({}),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  sourceId: uuid("source_id").references(() => sources.id),
  finishedAt: timestamp("finished_at", { withTimezone: true }),
  processed: integer("processed").notNull().default(0),
  imported: integer("imported").notNull().default(0),
  updated: integer("updated").notNull().default(0),
  skipped: integer("skipped").notNull().default(0),
  errors: integer("errors").notNull().default(0),
}, table => [index("import_job_source_time").on(table.sourceId, table.createdAt)]);
export const validationIssues = pgTable("validation_issues", {
  id: uuid("id").primaryKey().defaultRandom(),
  aedId: uuid("aed_id").references(() => aeds.id),
  rule: text("rule").notNull(),
  message: text("message").notNull(),
  resolved: boolean("resolved").notNull().default(false),
});
export const duplicateCandidates = pgTable("duplicate_candidates", {
  id: uuid("id").primaryKey().defaultRandom(),
  firstId: uuid("first_id").notNull().references(() => aeds.id),
  secondId: uuid("second_id").notNull().references(() => aeds.id),
  reason: text("reason").notNull(),
  status: text("status").notNull().default("pending"),
  score: integer("score").notNull().default(0),
  evidence: jsonb("evidence").$type<Record<string, unknown>>().notNull().default({}),
  blockingConflict: boolean("blocking_conflict").notNull().default(false),
});
export const auditLogs = pgTable("audit_logs", {
  id: uuid("id").primaryKey().defaultRandom(),
  userId: uuid("user_id").references(() => users.id),
  action: text("action").notNull(),
  entityId: uuid("entity_id"),
  isDemo: boolean("is_demo").notNull().default(false),
  details: jsonb("details").notNull().default({}),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const importErrors = pgTable("import_errors", {
  id: uuid("id").primaryKey().defaultRandom(),
  jobId: uuid("job_id").notNull().references(() => importJobs.id),
  sourceId: uuid("source_id").notNull().references(() => sources.id),
  sourceRecordId: text("source_record_id"),
  severity: text("severity").notNull(),
  rule: text("rule").notNull(),
  message: text("message").notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, table => [index("import_error_source_severity").on(table.sourceId, table.severity), index("import_error_time").on(table.createdAt)]);

export const dataConflicts = pgTable("data_conflicts", {
  id: uuid("id").primaryKey().defaultRandom(),
  aedId: uuid("aed_id").notNull().references(() => aeds.id),
  observationId: uuid("observation_id").notNull().references(() => observations.id),
  field: text("field").notNull(),
  currentValue: jsonb("current_value"),
  incomingValue: jsonb("incoming_value"),
  status: text("status").notNull().default("pending"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, table => [index("data_conflict_state").on(table.status)]);
